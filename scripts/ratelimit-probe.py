#!/usr/bin/env python3
"""Week 11: prove the gateway's local rate limit (token bucket: burst 200, refill 100/s).

Phase 1 — burst: N GET /api/catalog/products as fast as C workers can send them (≫ 100/s).
Phase 2 — steady: 50 req/s for 10 s, below the refill rate → must see 0 × 429.
Prints status codes per phase, the 429 response headers and the gateway's Envoy counters.
Usage: ratelimit-probe.py [env=staging] [burst=1000] [workers=50]
"""
import concurrent.futures as cf
import subprocess
import sys
import time
import json
import urllib.error
import urllib.parse
import urllib.request

env = sys.argv[1] if len(sys.argv) > 1 else "staging"
burst = int(sys.argv[2]) if len(sys.argv) > 2 else 1000
workers = int(sys.argv[3]) if len(sys.argv) > 3 else 50
host = f"{env}.shop.local"


def get(_):
    req = urllib.request.Request("http://127.0.0.1:8080/api/catalog/products", headers={"Host": host})
    try:
        with urllib.request.urlopen(req, timeout=10) as r:
            return r.status, None
    except urllib.error.HTTPError as e:
        return e.code, dict(e.headers)
    except Exception:  # noqa: BLE001
        return 0, None


def prom(q, at):
    url = "http://127.0.0.1:9090/api/v1/query?" + urllib.parse.urlencode({"query": q, "time": at})
    with urllib.request.urlopen(url, timeout=10) as r:
        return json.load(r)["data"]["result"]


pod = subprocess.run(["kubectl", "-n", f"shop-{env}", "get", "pod", "-l", "istio=shop-gateway", "-o",
                      "jsonpath={.items[0].metadata.name}"], capture_output=True, text=True).stdout
start = time.time()
print(f"# {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}  rate-limit probe against {host} (gateway {pod})")
print("# EnvoyFilter shop-gateway-ratelimit: token bucket max_tokens 200, tokens_per_fill 100, fill_interval 1s\n")

t0 = time.monotonic()
with cf.ThreadPoolExecutor(workers) as pool:
    res = list(pool.map(get, range(burst)))
dur = time.monotonic() - t0
codes = {}
for c, _h in res:
    codes[c] = codes.get(c, 0) + 1
print(f"## phase 1 — burst: {burst} requests in {dur:.2f} s ({burst / dur:.0f} req/s, {workers} workers)")
print(f"   status codes: {dict(sorted(codes.items()))}")
limited = next((h for c, h in res if c == 429), None)
if limited:
    print("   a 429 answer (generated by the gateway, the request never reached catalog):")
    low = {k.lower(): v for k, v in limited.items()}
    for k in ("x-local-rate-limit", "retry-after", "server", "content-length"):
        if k in low:
            print(f"     {k}: {low[k]}")
time.sleep(3)  # let the bucket refill

steady = []
t0 = time.monotonic()
with cf.ThreadPoolExecutor(20) as pool:
    futs = []
    for i in range(500):
        time.sleep(max(0, t0 + i / 50 - time.monotonic()))
        futs.append(pool.submit(get, i))
    steady = [f.result() for f in futs]
codes = {}
for c, _h in steady:
    codes[c] = codes.get(c, 0) + 1
print(f"\n## phase 2 — steady 50 req/s for 10 s (below the 100/s refill)\n   status codes: {dict(sorted(codes.items()))}")

# Istio's default stats matcher drops Envoy's http_local_rate_limiter.* counters, so the proof
# comes from the standard Istio metrics: what the gateway answered vs. what catalog received.
time.sleep(35)  # two scrape intervals
end = time.time()
win = f"{int(end - start)}s"
print(f"\n## Prometheus over the probe window ({win})")
for title, q in [
    ("gateway answers by code (reporter=source)",
     f'sum by (response_code) (increase(istio_requests_total{{namespace="shop-{env}",reporter="source",'
     f'source_workload="shop-gateway"}}[{win}]))'),
    ("requests that reached catalog (reporter=destination)",
     f'sum by (response_code) (increase(istio_requests_total{{namespace="shop-{env}",reporter="destination",'
     f'destination_workload=~"catalog.*",source_workload="shop-gateway"}}[{win}]))'),
]:
    print(f"   {title}")
    for r in sorted(prom(q, end), key=lambda r: r["metric"].get("response_code", "")):
        print(f"      {r['metric'].get('response_code', '-'):>5}  {float(r['value'][1]):7.0f}")
